import {test,expect} from '@playwright/test';
test('appearance switches all views, persists locally and keeps contact data',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'建立測試帳號',exact:true}).click();
  await page.getByLabel('姓名（必填）',{exact:true}).fill('外觀測試');
  await page.getByLabel('帳號 Email',{exact:true}).fill(`theme-${Date.now()}@example.test`);
  await page.getByLabel('密碼',{exact:true}).fill('Theme-test-password-2026!');
  await page.getByRole('button',{name:'建立帳號並登入',exact:true}).click();
  await page.getByRole('button',{name:'開啟功能選單',exact:true}).click(); await page.getByRole('button',{name:'外觀風格',exact:true}).click();
  await page.getByRole('radio',{name:'套用奶油手帳',exact:true}).click();
  await expect(page.getByRole('radio',{name:'套用奶油手帳',exact:true})).toBeChecked();
  await page.screenshot({path:'test-results/appearance-options.png',fullPage:true});
  await page.getByRole('button',{name:'⌂ 主頁',exact:true}).click();
  await expect(page.getByText('錢脈',{exact:true})).toHaveCSS('color','rgb(64, 61, 50)');
  await page.getByRole('button',{name:'＋ 新增聯絡人',exact:true}).first().click();
  await expect(page.getByLabel('姓名（必填）',{exact:true})).toHaveCSS('background-color','rgb(255, 249, 238)');
  await page.getByLabel('姓名（必填）',{exact:true}).fill('風格保留客戶');
  await page.getByRole('button',{name:'儲存',exact:true}).click();
  await expect(page.getByText('已儲存',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'返回上一頁',exact:true}).click();
  await page.reload();
  await expect(page.getByText('錢脈',{exact:true})).toHaveCSS('color','rgb(64, 61, 50)');
  await page.getByRole('button',{name:'開啟功能選單',exact:true}).click(); await page.getByRole('button',{name:'外觀風格',exact:true}).click();
  await page.getByRole('radio',{name:'套用清新氣泡',exact:true}).click();
  await expect(page.getByRole('radio',{name:'套用清新氣泡',exact:true})).toBeChecked();
  await page.getByRole('button',{name:'⌂ 主頁',exact:true}).click();
  await expect(page.getByText('錢脈',{exact:true})).toHaveCSS('color','rgb(33, 61, 80)');
  await page.screenshot({path:'test-results/appearance-bubble.png',fullPage:true});
  await page.getByRole('button',{name:'查看我的聯絡人 →',exact:true}).click();
  await expect(page.getByRole('button',{name:'查看 風格保留客戶',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'開啟功能選單',exact:true}).click(); await page.getByRole('button',{name:'外觀風格',exact:true}).click();
  await page.getByRole('radio',{name:'套用經典綠金',exact:true}).click();
  await expect(page.getByRole('radio',{name:'套用經典綠金',exact:true})).toBeChecked();
});
