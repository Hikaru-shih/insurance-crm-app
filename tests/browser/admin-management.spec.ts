import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
test('admin manages accounts, existing contacts and KPI settings', async ({page}) => {
  const email=`manager-${Date.now()}@example.test`, password='Browser-management-password!';
  execFileSync(process.execPath,['--import','tsx','-e',`const {createApi}=require('./server/app.ts'); const {emptyContact}=require('./src/domain/contacts.ts'); const {emptyWorkspace}=require('./src/domain/workspace.ts'); const app=createApi({database:process.env.TEST_DATABASE_PATH||'.data/browser-test.sqlite'}); app.createUser(process.env.TEST_ADMIN_EMAIL,process.env.TEST_ADMIN_PASSWORD,'admin').then(async()=>{const u=await app.createUser('managed-'+Date.now()+'@example.test',process.env.TEST_ADMIN_PASSWORD,'user','待管理使用者');const w=emptyWorkspace();w.contacts=[{...emptyContact(),id:'managed-contact',name:'既有客戶',createdAt:'2026-10-01',updatedAt:'2026-10-01'}];app.db.prepare('UPDATE workspaces SET data=? WHERE owner_id=?').run(JSON.stringify(w),u.id);app.db.close();}).catch(()=>process.exit(1));`],{env:{...process.env,TEST_ADMIN_EMAIL:email,TEST_ADMIN_PASSWORD:password}});
  await page.goto('/');
  await page.getByLabel('帳號 Email',{exact:true}).fill(email);
  await page.getByLabel('密碼',{exact:true}).fill(password);
  await page.getByRole('button',{name:'登入',exact:true}).click();
  await page.getByRole('button',{name:'開啟功能選單',exact:true}).click(); await page.getByRole('button',{name:'管理後台',exact:true}).click();
  await page.getByRole('button',{name:'＋ 建立帳號',exact:true}).click();
  await page.getByLabel('帳號姓名',{exact:true}).fill('新建管理測試');
  await page.getByLabel('新帳號 Email',{exact:true}).fill(`created-${Date.now()}@example.test`);
  await page.getByLabel('初始密碼（8–128 字元）',{exact:true}).fill(password);
  await page.getByRole('button',{name:'建立新帳號',exact:true}).click();
  await page.getByRole('button',{name:'確認儲存帳號',exact:true}).click();
  await expect(page.getByText('帳號設定',{exact:true})).toBeVisible();
  await page.getByLabel('帳號姓名',{exact:true}).fill('更新後姓名');
  await page.getByRole('button',{name:'設為停用',exact:true}).click();
  await page.getByRole('button',{name:'儲存帳號設定',exact:true}).click();
  await page.getByRole('button',{name:'確認儲存帳號',exact:true}).click();
  await expect(page.getByText('帳號設定已儲存',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'返回帳號列表',exact:true}).click();
  await page.getByLabel('搜尋帳號姓名或 Email',{exact:true}).fill('更新後姓名');
  await expect(page.getByRole('button',{name:/更新後姓名.*停用/})).toBeVisible();
  await page.getByLabel('搜尋帳號姓名或 Email',{exact:true}).fill('待管理使用者');
  await page.getByRole('button',{name:/待管理使用者.*查看資料/}).first().click();
  await page.getByRole('button',{name:'既有客戶 · 未分級',exact:true}).click();
  await page.getByRole('button',{name:'編輯此聯絡人',exact:true}).click();
  await page.getByLabel('姓名（必填）',{exact:true}).fill('老闆修改客戶');
  await page.getByRole('button',{name:'儲存',exact:true}).click();
  await expect(page.getByText('已儲存',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'返回上一頁',exact:true}).click();
  await page.getByRole('button',{name:'重新讀取帳號資料',exact:true}).click();
  await expect(page.getByRole('button',{name:'老闆修改客戶 · 未分級',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'返回帳號列表',exact:true}).click();
  const field=page.getByRole('textbox',{name:/分數$/}).first();
  const label=await field.getAttribute('aria-label');
  await field.fill('17');
  await page.getByRole('button',{name:'儲存'+label,exact:true}).click();
  await expect(page.getByText('分數已儲存',{exact:true})).toBeVisible();
  await page.reload();
  await page.getByRole('button',{name:'開啟功能選單',exact:true}).click(); await page.getByRole('button',{name:'管理後台',exact:true}).click();
  await expect(page.getByLabel(label!,{exact:true})).toHaveValue('17');
});
