import {test,expect} from '@playwright/test';
import {readdirSync,readFileSync} from 'node:fs';
import {join} from 'node:path';
test('employee menu shows private rank and changes password with mailed verification',async({page,request})=>{
 const api=process.env.TEST_API_URL??'http://127.0.0.1:3002',email=`menu-${Date.now()}@example.test`,password='Menu-original-password!';
 expect((await request.post(api+'/api/auth/register',{data:{name:'選單測試',email,password}})).status()).toBe(201);
 await page.goto('/');await page.getByLabel('帳號 Email',{exact:true}).fill(email);await page.getByLabel('密碼',{exact:true}).fill(password);await page.getByRole('button',{name:'登入',exact:true}).click();
 await expect(page.getByRole('button',{name:'外觀風格',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'開啟功能選單',exact:true}).click();
 await expect(page.getByRole('button',{name:'管理後台',exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'計分卡',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'關閉功能選單',exact:true}).click();
 await page.getByRole('button',{name:'▥ 計分卡',exact:true}).click();
 await expect(page.getByText(/本期第 \d+ 名／共 \d+ 人/)).toBeVisible();
 await expect(page.getByText('員工計分板',{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'開啟功能選單',exact:true}).click();
 await page.setViewportSize({width:390,height:844});await expect.poll(()=>page.getByText('功能選單',{exact:true}).evaluate(e=>{for(let x:Element|null=e;x;x=x.parentElement){if(Number(getComputedStyle(x).opacity)<1)return false;}return true;})).toBe(true);await page.screenshot({path:'test-results/account-menu.png'});
 await page.getByRole('button',{name:'帳號安全',exact:true}).click();
 await page.getByRole('button',{name:'寄送密碼重設信',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('若帳號符合條件');
 const dir=process.env.TEST_MAIL_OUTBOX??'.data/mail-outbox';
 const mail=readdirSync(dir).map(file=>JSON.parse(readFileSync(join(dir,file),'utf8'))).find(mail=>mail.to===email&&mail.subject.includes('重設密碼'));
 expect(mail).toBeTruthy();await page.getByLabel('8 位數驗證碼',{exact:true}).fill(mail.text.match(/\b\d{8}\b/)[0]);
 await page.getByLabel('新密碼（8–128 字元）',{exact:true}).fill('Menu-new-password!');
 await page.getByLabel('再次輸入新密碼',{exact:true}).fill('Menu-new-password!');
 await page.getByRole('button',{name:'確認重設密碼',exact:true}).click();
 await expect(page.getByLabel('帳號 Email',{exact:true})).toBeVisible();
 expect((await request.post(api+'/api/auth/login',{data:{email,password}})).status()).toBe(401);
 expect((await request.post(api+'/api/auth/login',{data:{email,password:'Menu-new-password!'}})).status()).toBe(200);
});
